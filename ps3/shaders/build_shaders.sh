#!/bin/sh
# Rebuilds ../source/ps3_shader_data.h from the Cg sources. Only needed when a
# shader changes: the header is committed, so building the port needs neither
# Cg nor cgcomp.
#
# Needs cgc (NVIDIA Cg Toolkit 3.1: apt-get install nvidia-cg-toolkit) and
# PSL1GHT's cgcomp ($PS3DEV/bin).
set -e
cd "$(dirname "$0")"
CGCOMP=${CGCOMP:-$PS3DEV/bin/cgcomp}
"$CGCOMP" -v mk64_vp.vcg mk64_vp.vpo
"$CGCOMP" -f mk64_fp_a.fcg mk64_fp_a.fpo
"$CGCOMP" -f mk64_fp_b.fcg mk64_fp_b.fpo
"$CGCOMP" -f mk64_fp_alpha.fcg mk64_fp_alpha.fpo
python3 - <<'PY'
def arr(name, path):
    d = open(path, 'rb').read()
    rows = [', '.join('0x%02x' % b for b in d[i:i + 12]) for i in range(0, len(d), 12)]
    return ('static const unsigned char %s[] __attribute__((aligned(16))) = {\n  %s\n};\n'
            % (name, ',\n  '.join(rows)))
out = ('/* ps3_shader_data.h -- the RSX shaders, PRECOMPILED.\n'
       ' *\n'
       ' * Generated by shaders/build_shaders.sh from the .vcg and\n'
       ' * .fcg files in shaders/. Do not edit.\n'
       ' */\n'
       '#ifndef PS3_SHADER_DATA_H\n#define PS3_SHADER_DATA_H\n\n'
       + arr('shader_vp_data', 'mk64_vp.vpo') + '\n'
       + arr('shader_fp_a_data', 'mk64_fp_a.fpo') + '\n'
       + arr('shader_fp_b_data', 'mk64_fp_b.fpo') + '\n'
       + arr('shader_fp_alpha_data', 'mk64_fp_alpha.fpo') + '\n'
       '#endif /* PS3_SHADER_DATA_H */\n')
open('../source/ps3_shader_data.h', 'w').write(out)
PY
rm -f mk64_vp.vpo mk64_fp_a.fpo mk64_fp_b.fpo mk64_fp_alpha.fpo
echo "wrote ../source/ps3_shader_data.h"
