#!/usr/bin/env python3
"""Writes ps3/gen/n64_symbols.S: the address of every symbol that the game
code refers to but that is not compiled into the PS3 binary, because the data
behind it is read from the user's ROM at run time.

Those symbols are either segmented addresses (0x02xxxxxx, 0x0Dxxxxxx, ...) of
data inside a ROM segment, or offsets into the ROM itself
(_xxxSegmentRomStart). Their values are fixed: they are the ones of the
matching build of the USA ROM.

Only needed when the set of symbols the game code uses changes. Inputs:

  undefined.txt   symbols left undefined by a partial link of the game objects
                  (ppu-ld -r ... && ppu-nm | awk '$1=="U"')
  n64syms.txt     "address type name" for the matching N64 build: nm of
                  mk64.us.elf and of every other .elf under build/us

    python3 ps3/tools/gen_n64_symbols.py undefined.txt n64syms.txt > ps3/gen/n64_symbols.S
"""
import sys

undef = [l.strip().lstrip('.') for l in open(sys.argv[1]) if l.strip()]
syms = {}
for l in open(sys.argv[2]):
    a, t, n = l.split()
    syms.setdefault(n, set()).add(int(a, 16))

out, skipped = [], []
for u in sorted(set(undef)):
    if u not in syms:
        skipped.append(u)
        continue
    vals = syms[u]
    if len(vals) != 1:
        sys.exit("ambiguous symbol %s: %s" % (u, sorted(vals)))
    a = next(iter(vals))
    if (a >> 24) == 0x80 or (a >> 24) >= 0x10:
        skipped.append(u)       # N64 code/bss: has a native replacement
        continue
    out.append((a, u))

print("/* Generated by ps3/tools/gen_n64_symbols.py -- do not edit. */")
print("/* %d symbols: segmented addresses and ROM offsets of the USA ROM. */" % len(out))
for a, u in sorted(out):
    print(".globl %s\n%s = 0x%08X" % (u, u, a))
sys.stderr.write("%d symbols written, %d left for native code:\n%s\n" % (len(out), len(skipped), " ".join(skipped)))
