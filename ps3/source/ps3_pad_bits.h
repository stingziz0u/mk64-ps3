/* ps3_pad_bits.h -- the DualShock 3 button bits, with no PSL1GHT types, for
 * the game side (see ps3_plat.h). Same values as PAD_* in ps3_pad.h. */

#ifndef PS3_PAD_BITS_H
#define PS3_PAD_BITS_H

#define PS3PAD_LEFT      0x8000
#define PS3PAD_DOWN      0x4000
#define PS3PAD_RIGHT     0x2000
#define PS3PAD_UP        0x1000
#define PS3PAD_START     0x0800
#define PS3PAD_R3        0x0400
#define PS3PAD_L3        0x0200
#define PS3PAD_SELECT    0x0100
#define PS3PAD_SQUARE    0x0080
#define PS3PAD_CROSS     0x0040
#define PS3PAD_CIRCLE    0x0020
#define PS3PAD_TRIANGLE  0x0010
#define PS3PAD_R1        0x0008
#define PS3PAD_L1        0x0004
#define PS3PAD_R2        0x0002
#define PS3PAD_L2        0x0001

#endif /* PS3_PAD_BITS_H */
